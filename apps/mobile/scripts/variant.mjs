import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const state = path.join(root, "variant.json");
const variant = process.argv[2] || JSON.parse(fs.readFileSync(state, "utf8")).variant;
if (!["broken", "fixed"].includes(variant)) throw new Error("Expected broken or fixed");
const pkg = JSON.parse(fs.readFileSync(path.join(root, "node_modules/react-native-webview/package.json"), "utf8"));
if (pkg.version !== "13.16.2") throw new Error("Refusing to patch WebView " + pkg.version);
const file = path.join(root, "node_modules/react-native-webview/apple/RNCWebViewImpl.m");
let code = fs.readFileSync(file, "utf8");
const broken = "if (request.URL.host) {";
const fixed = "if (!request.URL.isFileURL) {";
const count = token => code.split(token).length - 1;
if (count(broken) + count(fixed) !== 1) throw new Error("Unexpected native source; inspect before patching");
code = code.replace(variant === "fixed" ? broken : fixed, variant === "fixed" ? fixed : broken);
fs.writeFileSync(file, code);
fs.writeFileSync(state, JSON.stringify({ variant }, null, 2) + "\n");
console.log("Prepared " + variant + " JS configuration and native WebView source. Rebuild iOS; Fast Refresh is not sufficient.");
